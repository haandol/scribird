import Foundation

/// 캡처가 조용히 실패했는지 판정하는 기준.
///
/// 두 소스가 같은 판정을 거치지만 유예 시간만 다르므로, 그 차이를 코드 한곳에 모아
/// 둔다. 액터에 매인 상태가 아니라 순수한 값이라 판정 함수와 함께 여기 둔다.
enum SilenceCriteria {
    /// 무음으로 볼 최대 진폭. 이보다 작으면 소리가 한 번도 들어오지 않았다는 뜻이다.
    ///
    /// 발화 게이트(0.003, 약 -50 dBFS)보다 훨씬 낮게 잡는다. 게이트 수준으로 올리면
    /// 아주 작게 녹음된 정상 세션이 권한 거부로 오진된다.
    static let threshold: Float = 0.0005

    /// 무음 판정을 시작하기까지 기다리는 시간(초).
    ///
    /// 소스별로 다르다. 마이크는 사용자가 말하기 시작하면 곧 소리가 들어오지만,
    /// 시스템 출력은 **재생 중인 소리가 원래 없을 수도** 있어 더 오래 기다려야
    /// 정상 상태를 무음으로 오진하지 않는다. 그래서 두 값을 맞바꾸면 조용한 회의
    /// 도입부에서 시스템 오디오에 잘못된 경고가 뜬다.
    static func gracePeriod(for speaker: Speaker) -> TimeInterval {
        switch speaker {
        case .me: 4
        case .remote: 8
        }
    }
}
