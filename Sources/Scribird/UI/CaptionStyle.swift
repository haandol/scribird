import SwiftUI

/// 본문 아래 붙는 보조 설명의 서식.
///
/// 이 앱의 화면은 대부분 **설명이 딸린 한 줄**로 이루어져 있다 — 잠긴 이유, 단축키의 동작
/// 범위, 폴더를 여는 조건. 그 설명들이 같은 크기로 보여야 사용자가 "이건 부가 설명"이라고
/// 한 번만 학습한다. 크기를 호출처마다 적으면 한 곳만 다르게 고쳐졌을 때 그 줄이 본문처럼
/// 읽힌다.
///
/// 색은 넘겨받는다. 같은 자리에 서는 설명이라도 안내(`.secondary`)와 경고(`.orange`)는
/// 구분돼야 하고, 그 구분이 이 서식의 목적은 아니다.
extension View {
    /// 크기 11의 보조 설명 서식.
    ///
    /// 색을 항상 적게 한다 — 생략할 수 있게 두면 안내와 경고 중 어느 것인지가 호출처에서
    /// 보이지 않고, 그 구분이 이 자리에서 사용자가 읽어야 하는 것이다.
    func captionStyle(_ style: some ShapeStyle) -> some View {
        captionSize().foregroundStyle(style)
    }

    /// 색을 바꾸지 않는 보조 설명. 링크 버튼처럼 자기 색을 이미 가진 것에 쓴다.
    func captionSize() -> some View {
        font(.system(size: 11))
    }
}
